#!/usr/bin/env python3
"""Bundle the prototype into one self-contained HTML file and regenerate docs/REVIEW_CHECKLIST.md.

    python3 build.py

Outputs
  dist/thin-walled-faq-lab.html   full standalone page (Canvas upload / email / offline)
  dist/beat-your-best.html        the game, standalone (pass --library-url URL to link it to a hosted library)
  docs/QUESTION_BANK.md           every game question with answer key and source reference (needs node)
  docs/REVIEW_CHECKLIST.md        generated from the `review` arrays in data/*.js (needs node)
"""
import base64, json, pathlib, re, shutil, subprocess

ROOT = pathlib.Path(__file__).parent
DIST = ROOT / 'dist'


def inline(html: str) -> str:
    def css(m):
        return '<style>\n' + (ROOT / m.group(1)).read_text() + '\n</style>'
    html = re.sub(r'<link rel="stylesheet" href="(css/[^"]+)">', css, html)

    def js(m):
        code = (ROOT / m.group(1)).read_text()
        mime = {'png': 'image/png', 'webp': 'image/webp', 'jpg': 'image/jpeg', 'svg': 'image/svg+xml'}
        code = re.sub(r'assets/figures/([\w\-]+)\.(png|webp|jpg|svg)',
                      lambda f: f'data:{mime[f.group(2)]};base64,' + base64.b64encode((ROOT / 'assets/figures' / f'{f.group(1)}.{f.group(2)}').read_bytes()).decode(), code)
        # figures referenced by name through the fig() helper in data files
        code = re.sub(r"(fig\('[^']+', ')([\w\-]+)(')",
                      lambda f: f[1] + 'data:image/webp;base64,' + base64.b64encode((ROOT / 'assets/figures' / f'{f[2]}.webp').read_bytes()).decode() + f[3], code)
        return '<script>\n' + code.replace('</script', '<\\/script') + '\n</script>'
    return re.sub(r'<script src="((?:data|js|game)/[^"]+)"></script>', js, html)


def checklist():
    if not shutil.which('node'):
        print('node not found: skipping REVIEW_CHECKLIST.md')
        return
    scripts = re.findall(r'<script src="(data/[^"]+)"></script>', (ROOT / 'index.html').read_text())
    scripts = [x for x in scripts if 'taxonomy' in x or 'notation' in x] + [x for x in scripts if 'taxonomy' not in x and 'notation' not in x]
    prog = 'global.window={};' + ''.join(f'require({json.dumps(str(ROOT / s))});' for s in scripts) + \
           'console.log(JSON.stringify(window.FAQ_REGISTRY.map(f=>({id:f.id,order:f.order,status:f.status,discussion:f.discussion,pages:f.pages,heading:f.card.heading,review:f.review,topic:f.meta&&f.meta.topic,title:f.meta?f.meta.title:f.card.heading,activity:f.card.activity,minutes:f.card.minutes,steps:(f.steps||[]).length,threads:[{d:f.discussion,p:f.pages,t:f.source.title},...((f.source.threads||[]).map(t=>({d:t.discussion,p:t.pages,t:t.title})))]}))))'
    data = sorted(json.loads(subprocess.check_output(['node', '-e', prog])), key=lambda f: f['order'])
    out = ['# Academic review checklist', '',
           '_Generated by `build.py` from the `review` arrays in `data/*.js`. Edit those, not this file._', '',
           'Sign off each item before changing an activity’s `status` to `approved`.', '',
           '## Applies to every activity', '',
           '- [ ] Source text is verbatim and complete, with anonymisation the only change (compare with the PDF pages listed).',
           '- [ ] No student names or identifying details remain in text, figures or alt text.',
           '- [ ] Every answer marked correct is consistent with the academic’s explanation, and every distractor is clearly wrong.',
           '- [ ] Activity prompts (marked “Added for revision”) don’t introduce new engineering claims.',
           '- [ ] Diagrams and alt text represent the engineering correctly.',
           '- [ ] Intended learning outcomes are supported (Learning Technologist to confirm).', '']
    for f in data:
        out += [f"## {f['heading']} (Discussion #{f['discussion']}, pp. {f['pages']})", '', f"Current status: `{f['status']}`", '']
        out += [f"- [ ] **{r['area']}:** {r['item']}" for r in f['review']] + ['']
    (ROOT / 'docs/REVIEW_CHECKLIST.md').write_text('\n'.join(out))
    print('wrote docs/REVIEW_CHECKLIST.md')
    topics = {t['id']: t['label'] for t in json.loads(subprocess.check_output(['node', '-e', 'global.window={};require(' + json.dumps(str(ROOT / 'data/taxonomy.js')) + ');console.log(JSON.stringify(window.FAQ_TAXONOMY.subjects[0].modules[0].topics))']))}
    cm = ['# Content map', '', '_Generated by `build.py`. Every discussion thread in the 2023/24 PDF and the resource it appears in._', '',
          f"{len(data)} resources ({sum(1 for f in data if f['steps'])} interactive activities, {sum(1 for f in data if not f['steps'])} quick answers) covering {len({t['d'] for f in data for t in f['threads']})} threads.", '']
    for tid, label in topics.items():
        rs = [f for f in data if f['topic'] == tid]
        if not rs: continue
        cm += [f'## {label}', '', '| Resource | Type | Threads (PDF pages) |', '|---|---|---|']
        for f in rs:
            th = '; '.join(f"#{t['d']} {t['t']} (p. {t['p']})" for t in f['threads'])
            cm.append(f"| {f['title']} | {f['activity']}, {f['minutes']} min | {th} |")
        cm.append('')
    (ROOT / 'docs/CONTENT_MAP.md').write_text('\n'.join(cm))
    print('wrote docs/CONTENT_MAP.md')


def question_bank():
    if not shutil.which('node'):
        print('node not found: skipping QUESTION_BANK.md'); return
    out = subprocess.run(['node', str(ROOT / 'tests/game-bank.js'), '--markdown'], capture_output=True, text=True, cwd=ROOT)
    if out.returncode:
        print(out.stderr); raise SystemExit('question bank check failed')
    (ROOT / 'docs/QUESTION_BANK.md').write_text(out.stdout)
    print('wrote docs/QUESTION_BANK.md')


if __name__ == '__main__':
    import sys
    DIST.mkdir(exist_ok=True)
    page = inline((ROOT / 'index.html').read_text())
    (DIST / 'thin-walled-faq-lab.html').write_text(page)
    print(f"wrote dist/thin-walled-faq-lab.html ({len(page) // 1024} KB)")
    game = (ROOT / 'game.html').read_text()
    if '--library-url' in sys.argv:
        url = sys.argv[sys.argv.index('--library-url') + 1]
        game = game.replace("libraryUrl: 'index.html'", f"libraryUrl: {json.dumps(url)}")
    game = inline(game)
    (DIST / 'beat-your-best.html').write_text(game)
    print(f"wrote dist/beat-your-best.html ({len(game) // 1024} KB)")
    checklist()
    question_bank()
