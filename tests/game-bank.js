/* Checks the Beat Your Best question bank and (with --markdown) prints docs/QUESTION_BANK.md.
 *   node tests/game-bank.js            integrity + coverage checks, exit 1 on failure
 *   node tests/game-bank.js --markdown reviewer document on stdout
 */
const fs = require('fs'), vm = require('vm'), path = require('path');
const ROOT = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'game.html'), 'utf8');
const ctx = { window: {} }; ctx.window.window = ctx.window; vm.createContext(ctx);
for (const m of html.matchAll(/<script src="((?:data|game)\/[^"]+)"><\/script>/g)) if (!m[1].endsWith("engine.js")) vm.runInContext(fs.readFileSync(path.join(ROOT, m[1]), 'utf8'), ctx, { filename: m[1] });
const { questions: Q, problems } = ctx.window.GAME_BANK;
const T = ctx.window.FAQ_TAXONOMY;
const text = s => String(s || '').replace(/<[^>]+>/g, '').replace(/&gt;/g, '>').replace(/&lt;/g, '<').replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
const fail = [...problems];
const ids = new Set();
Q.forEach(q => {
  if (ids.has(q.id)) fail.push('duplicate id ' + q.id); ids.add(q.id);
  if (![1, 2, 3].includes(q.level)) fail.push(q.id + ': bad level');
  if (!q.src.length) fail.push(q.id + ': no PDF source');
  if ((q.type === 'mcq' || q.type === 'multi') && !q.options.some(o => o.correct)) fail.push(q.id + ': no correct option');
  if (q.type === 'mcq' && q.options.filter(o => o.correct).length !== 1) fail.push(q.id + ': single-answer question with ' + q.options.filter(o => o.correct).length + ' correct options');
  if (q.type === 'tf' && q.reasons.filter(r => r.correct).length !== 1) fail.push(q.id + ': tf needs exactly one correct reason');
  if (q.type === 'numeric' && (!q.units.includes(q.unit) || !q.worked)) fail.push(q.id + ': numeric needs unit in list and worked solution');
});
// every Beat Your Best challenge / final mix must be fillable
const pool = (topics, l) => Q.filter(q => q.level === l && q.topic !== 'info' && (!topics || topics.includes(q.topic))).length;
[[['t3'], [3, 3, 2]], [['t1', 't2', 't5', 't7'], [3, 3, 2]], [['pre', 't4'], [3, 3, 2]], [['t6', 't8'], [3, 3, 2]], [null, [4, 4, 2]], [null, [6, 8, 6]]]
  .forEach(([t, mix]) => mix.forEach((n, i) => { const have = pool(t, i + 1); if (have < n * 1.5) fail.push(`challenge ${t || 'all'} level ${i + 1}: only ${have} questions for ${n} per attempt (want ≥ 1.5× for variety)`); }));

if (process.argv.includes('--markdown')) {
  const LV = { 1: 'Foundation', 2: 'Application', 3: 'Reasoning' };
  const topicLabel = id => T.subjects[0].modules[0].topics.find(t => t.id === id).label;
  const key = q => {
    switch (q.type) {
      case 'mcq': case 'multi': return q.options.filter(o => o.correct).map(o => text(o.html)).join(' / ');
      case 'tf': return `${q.truth ? 'TRUE' : 'FALSE'}. Reason: ${text(q.reasons.find(r => r.correct).html)}`;
      case 'sort': return q.items.map(i => `${text(i.html)} → ${q.categories.find(c => c.id === i.cat).label}`).join('; ');
      case 'order': return q.items.map((i, n) => `(${n + 1}) ${text(i.html)}`).join(' ');
      case 'match': return q.pairs.map(p => `${text(p.left)} ↔ ${text(p.right)}`).join('; ');
      case 'numeric': return `${q.answer} ${q.unit} (tolerance ${q.tol.abs != null ? '±' + q.tol.abs : '±' + q.tol.rel * 100 + '%'})`;
    }
  };
  const L = ['# Beat Your Best: question bank', '',
    `Generated by \`build.py\`. ${Q.length} questions, all **awaiting academic review**. Check each answer key against the quoted source blocks, and each level against the description in docs/GAME.md.`, '',
    '- [ ] = not yet reviewed. Tick when the question, answer key, level and explanation are confirmed.', '- *Origin* `new` = written for the game from the academic\'s explanation. Anything else = a checked step from a library activity.', ''];
  T.subjects[0].modules[0].topics.forEach(t => {
    const qs = Q.filter(q => q.topic === t.id).sort((a, b) => a.level - b.level);
    if (!qs.length) return;
    L.push(`## ${topicLabel(t.id)} (${qs.length})`, '');
    qs.forEach(q => {
      L.push(`- [ ] **${q.id}** · ${LV[q.level]} · ${q.type}${q.kind ? ' (' + q.kind + ')' : ''} · origin: \`${q.origin}\``);
      L.push(`  - Q: ${text(q.prompt)}`);
      L.push(`  - A: ${text(key(q))}`);
      if (q.worked) L.push(`  - Worked solution (added): ${text(q.worked)}`);
      if (q.note) L.push(`  - Note: ${text(q.note)}`);
      L.push(`  - Source: ${q.src.map(s => `#${s.disc} (PDF p. ${s.pages})`).join(', ')} · blocks ${q.refs.map(r => r.faq + ': ' + r.ids.join(', ')).join('; ')}`);
    });
    L.push('');
  });
  process.stdout.write(L.join('\n'));
} else {
  const by = k => Q.reduce((m, q) => (m[q[k]] = (m[q[k]] || 0) + 1, m), {});
  console.log(`${Q.length} questions`, by('type'), by('level'));
}
if (fail.length) { console.error('FAIL\n' + fail.join('\n')); process.exit(1); }
else if (!process.argv.includes('--markdown')) console.log('All checks passed.');
